/* ---------- 生成日期列表（10/4 → 12/18，共 76 天） ---------- */
function buildDates(start, n) {
  const out = [];
  const d = new Date(start + 'T00:00:00');
  for (let i = 0; i < n; i++) {
    const y = d.getFullYear();
    const m = String(d.getMonth() + 1).padStart(2, '0');
    const day = String(d.getDate()).padStart(2, '0');
    out.push(`${y}-${m}-${day}`);
    d.setDate(d.getDate() + 1);
  }
  return out;
}

const DATES = buildDates('2026-10-04', 76);

/* 用阶段的起止月/日构造完整日期做比较 */
function phaseStartDate(p) {
  const [m, d] = p.range.split('-')[0].trim().split('/').map(Number);
  return `2026-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
}
function phaseEndDate(p) {
  const [m, d] = p.range.split('-')[1].trim().split('/').map(Number);
  return `2026-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
}
function phaseOfDate(date) {
  return PHASES.find(p => date >= phaseStartDate(p) && date <= phaseEndDate(p)) || null;
}

